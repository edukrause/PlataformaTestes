CREATE TABLE lote (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(160) NOT NULL,
  criado_em VARCHAR(40) NOT NULL,
  status VARCHAR(30) NOT NULL
);
CREATE TABLE lote_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lote_id BIGINT NOT NULL REFERENCES lote(id),
  chave_jira VARCHAR(80) NOT NULL,
  execucao_id BIGINT REFERENCES execucao(id),
  status VARCHAR(30) NOT NULL,
  mensagem VARCHAR(1000)
);
CREATE TABLE publicacao_jira (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id BIGINT NOT NULL REFERENCES execucao(id),
  revisao_id BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL,
  comentario_id VARCHAR(160),
  criada_em VARCHAR(40) NOT NULL,
  UNIQUE(execucao_id,revisao_id)
);
