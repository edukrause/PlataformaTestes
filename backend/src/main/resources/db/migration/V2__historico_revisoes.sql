-- Revisão corrente continua em revisao; todas as decisões ficam preservadas nesta trilha.
CREATE TABLE historico_revisao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id BIGINT NOT NULL REFERENCES execucao(id),
  analista VARCHAR(120) NOT NULL,
  decisao VARCHAR(30) NOT NULL,
  valores_alterados INT NOT NULL,
  tempo_revisao_s BIGINT NOT NULL,
  comentario CLOB NOT NULL,
  registrada_em VARCHAR(40) NOT NULL
);
CREATE INDEX idx_historico_revisao_execucao ON historico_revisao(execucao_id, id);

-- Preserva as revisões de quem já executou a V1 antes desta atualização.
INSERT INTO historico_revisao(execucao_id,analista,decisao,valores_alterados,tempo_revisao_s,comentario,registrada_em)
SELECT execucao_id,analista,decisao,valores_alterados,tempo_revisao_s,comentario,registrada_em FROM revisao;
