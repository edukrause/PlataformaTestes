-- Tarefa é um retrato por coleta: duas execuções não sobrescrevem requisitos históricos.
CREATE TABLE tarefa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chave_jira VARCHAR(80) NOT NULL,
  titulo VARCHAR(1000) NOT NULL,
  area VARCHAR(30) NOT NULL,
  requisito CLOB NOT NULL,
  documentacao_ref VARCHAR(2000),
  hash_documentacao VARCHAR(64),
  coletada_em VARCHAR(40) NOT NULL,
  demanda_json CLOB NOT NULL
);
CREATE INDEX idx_tarefa_chave ON tarefa(chave_jira);
CREATE TABLE execucao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarefa_id BIGINT NOT NULL REFERENCES tarefa(id),
  versao_prompt VARCHAR(80) NOT NULL,
  status VARCHAR(30) NOT NULL,
  etapa VARCHAR(30) NOT NULL,
  exige_apuracao BOOLEAN NOT NULL DEFAULT FALSE,
  tempo_total_ms BIGINT NOT NULL DEFAULT 0,
  custo_total_usd DECIMAL(20,10) NOT NULL DEFAULT 0,
  iniciada_em VARCHAR(40) NOT NULL,
  pontos_atencao_json CLOB NOT NULL DEFAULT '[]',
  mensagem_erro VARCHAR(1000)
);
CREATE TABLE cenario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id BIGINT NOT NULL REFERENCES execucao(id),
  tipo VARCHAR(30) NOT NULL,
  titulo VARCHAR(1000) NOT NULL,
  gherkin CLOB NOT NULL,
  resultado_esperado CLOB NOT NULL,
  sintaxe_valida BOOLEAN NOT NULL,
  execucao_teste_json CLOB
);
-- Reservadas para o módulo 2. Nenhuma consulta é executada nesta entrega.
CREATE TABLE apuracao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id BIGINT NOT NULL REFERENCES execucao(id),
  cenario_id BIGINT REFERENCES cenario(id),
  pergunta CLOB NOT NULL,
  subesquema CLOB NOT NULL,
  desfecho VARCHAR(30) NOT NULL,
  resultado_referencia CLOB
);
CREATE TABLE candidato_sql (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  apuracao_id BIGINT NOT NULL REFERENCES apuracao(id),
  provedor VARCHAR(30) NOT NULL,
  modelo VARCHAR(160) NOT NULL,
  tentativa INT NOT NULL,
  consulta CLOB NOT NULL,
  verificacao VARCHAR(40) NOT NULL,
  hash_resultado VARCHAR(64),
  tokens_entrada INT NOT NULL,
  tokens_saida INT NOT NULL,
  custo_usd DECIMAL(20,10) NOT NULL,
  latencia_ms BIGINT NOT NULL
);
CREATE TABLE revisao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id BIGINT NOT NULL UNIQUE REFERENCES execucao(id),
  analista VARCHAR(120) NOT NULL,
  decisao VARCHAR(30) NOT NULL,
  valores_alterados INT NOT NULL,
  tempo_revisao_s BIGINT NOT NULL,
  comentario CLOB NOT NULL,
  registrada_em VARCHAR(40) NOT NULL
);
-- Auditoria de geração de cenários separada de candidatos SQL, para não misturar métricas.
CREATE TABLE chamada_modelo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id BIGINT NOT NULL REFERENCES execucao(id),
  provedor VARCHAR(30) NOT NULL,
  modelo VARCHAR(160) NOT NULL,
  prompt_enviado CLOB NOT NULL,
  resposta CLOB NOT NULL,
  correspondencias_json CLOB NOT NULL,
  tokens_entrada INT NOT NULL,
  tokens_saida INT NOT NULL,
  latencia_ms BIGINT NOT NULL,
  custo_usd DECIMAL(20,10) NOT NULL
);
CREATE TABLE conversa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(120) NOT NULL,
  criada_em VARCHAR(40) NOT NULL
);
CREATE TABLE mensagem (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversa_id BIGINT NOT NULL REFERENCES conversa(id),
  papel VARCHAR(30) NOT NULL,
  texto CLOB NOT NULL,
  enviada_em VARCHAR(40) NOT NULL,
  execucao_id BIGINT REFERENCES execucao(id)
);
